-- Практика 9. Формування запитів з групуванням даних
-- Схема: books (вимір 1), readers (вимір 2), loans (факт)

-- Завдання 1: GROUP BY по зовнішньому ключу (скільки видач у кожної книги, за id)
SELECT book_id, COUNT(*) AS кількість_видач
FROM loans
GROUP BY book_id;
-- результат (book_id | кількість): 1|2, 2|2, 3|2, 4|2, 5|1, 6|1

-- Завдання 2: зрозуміла версія через LEFT JOIN + GROUP BY (групуємо за первинним ключем books.id)
SELECT books.title AS книга, COUNT(loans.id) AS кількість_видач
FROM books
LEFT JOIN loans ON loans.book_id = books.id
GROUP BY books.id;
-- результат:
-- Кобзар 2; Тигролови 2; Захар Беркут 2; Земля 2; Місто 1; Собор 1;
-- Українська мова. Практикум 0

-- Завдання 3: кілька агрегатних функцій в одній групі
SELECT books.title AS книга,
       COUNT(loans.id)      AS кількість_видач,
       MIN(loans.loan_date) AS перша_видача,
       MAX(loans.loan_date) AS остання_видача
FROM books
LEFT JOIN loans ON loans.book_id = books.id
GROUP BY books.id;
-- результат:
-- Кобзар                     | 2 | 2026-01-05 | 2026-03-01
-- Тигролови                  | 2 | 2026-02-01 | 2026-05-01
-- Захар Беркут               | 2 | 2026-02-10 | 2026-05-10
-- Земля                      | 2 | 2026-03-15 | 2026-06-01
-- Місто                      | 1 | 2026-04-02 | 2026-04-02
-- Собор                      | 1 | 2026-04-20 | 2026-04-20
-- Українська мова. Практикум | 0 | NULL       | NULL

-- Завдання 4: GROUP BY за двома виразами (місяць видачі + чи книга ще на руках)
SELECT strftime('%m', loan_date) AS місяць,
       return_date IS NULL       AS на_руках,   -- 1 = ще не повернуто, 0 = повернуто
       COUNT(*)                  AS кількість
FROM loans
GROUP BY strftime('%m', loan_date), return_date IS NULL;
-- результат: 10 рядків
-- (місяць, на_руках, кількість): 01,0,1; 02,0,1; 02,1,1; 03,0,1; 03,1,1;
-- 04,0,1; 04,1,1; 05,0,1; 05,1,1; 06,1,1

-- Завдання 5: пастка «колонка поза GROUP BY» (loan_date не в GROUP BY і не під агрегатом)
SELECT book_id, loan_date, COUNT(*) AS кількість
FROM loans
GROUP BY book_id;
